package com.catalystflow.e2e.support;

import io.restassured.http.ContentType;
import io.restassured.response.Response;

import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import static io.restassured.RestAssured.given;
import static org.junit.jupiter.api.Assertions.assertNotNull;

/**
 * Helpers for creating review-domain entities (templates, cycles, reviews) via
 * the real API. Each creation also registers the resulting ID with
 * {@link TestFixtures} so the run-level teardown wipes it from DynamoDB.
 *
 * Methods that need a token take it explicitly — usually
 * {@code fixtures.admin.token()}. Keeping the helpers static + token-explicit
 * avoids hidden state and makes the call sites read like the API contract.
 */
public final class ReviewTestHelpers {
    private static final java.time.LocalDate TEST_DAY = java.time.LocalDate.now(java.time.ZoneId.of("Australia/Sydney"));
    public static final String CYCLE_START = TEST_DAY.minusDays(1).format(java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy"));
    public static final String CYCLE_DUE = TEST_DAY.plusDays(30).format(java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy"));


    private ReviewTestHelpers() {}

    // ── Templates ─────────────────────────────────────────────────────────────

    /**
     * Creates a minimal review template via POST /templates and registers it
     * for teardown. The caller token must be ADMIN.
     */
    public static String createTemplate(TestFixtures fx, String token, String reviewType) {
        String questionId = UUID.randomUUID().toString();

        Map<String, Object> question = new HashMap<>();
        question.put("questionId", questionId);
        question.put("text", "How did the employee perform?");
        question.put("type", "TEXT");
        question.put("required", true);
        question.put("order", 1);

        Map<String, Object> body = new HashMap<>();
        body.put("templateName", "E2E " + reviewType + " " + uniqueSuffix());
        body.put("reviewType", reviewType);
        body.put("description", "Generated by E2E test run " + E2EConfig.RUN_ID);
        body.put("questions", List.of(question));

        String templateId = given()
                .header("Authorization", "Bearer " + token)
                .contentType(ContentType.JSON)
                .body(body)
                .when()
                .post("/templates")
                .then()
                .statusCode(201)
                .extract().path("templateId");

        assertNotNull(templateId, "POST /templates must return a templateId");
        fx.registerTemplateForCleanup(templateId);
        return templateId;
    }

    /**
     * Returns the questionId of the first question on a template — useful when
     * a test needs to submit answers but did not create the template itself.
     */
    public static String firstQuestionId(String token, String templateId) {
        return given()
                .header("Authorization", "Bearer " + token)
                .when()
                .get("/templates/" + templateId)
                .then()
                .statusCode(200)
                .extract().path("questions[0].questionId");
    }

    // ── Cycles ────────────────────────────────────────────────────────────────

    /**
     * Creates a minimal review cycle in DRAFT state and registers it for
     * teardown. The cycle includes ONE valid SELF milestone — publishCycle()
     * refuses to transition DRAFT → SCHEDULED without at least one milestone
     * that has name + assignedRoles + startDate + endDate inside the cycle
     * range (see ReviewCycleService.validatePublishableMilestones).
     *
     * No templateSnapshot is attached, so peer360Required stays false for
     * the manager-gate tests that depend on the "no 360 in this cycle" case.
     */
    public static String createDraftCycle(TestFixtures fx, String token, String templateId) {
        Map<String, Object> milestone = new HashMap<>();
        milestone.put("milestoneId",   "m-" + uniqueSuffix());
        milestone.put("name",          "Self Review");
        milestone.put("assignedRoles", List.of("EMPLOYEE"));
        milestone.put("startDate",     CYCLE_START);
        milestone.put("endDate",       CYCLE_DUE);

        Map<String, Object> body = new HashMap<>();
        body.put("cycleTitle", "E2E Cycle " + uniqueSuffix());
        body.put("templateId", templateId);
        body.put("startDate",  CYCLE_START);
        body.put("dueDate",    CYCLE_DUE);
        body.put("milestones", List.of(milestone));

        String cycleId = given()
                .header("Authorization", "Bearer " + token)
                .contentType(ContentType.JSON)
                .body(body)
                .when()
                .post("/cycles")
                .then()
                .statusCode(201)
                .extract().path("cycleId");

        assertNotNull(cycleId, "POST /cycles must return a cycleId");
        fx.registerCycleForCleanup(cycleId);
        return cycleId;
    }

    /** Transition cycle DRAFT → SCHEDULED. */
    public static void publishCycle(String token, String cycleId) {
        // Cycle resource is class-level @Consumes(APPLICATION_JSON); even body-less
        // POSTs must declare Content-Type or Quarkus answers 415 before the handler runs.
        given()
                .header("Authorization", "Bearer " + token)
                .contentType(ContentType.JSON)
                .when()
                .post("/cycles/" + cycleId + "/publish")
                .then()
                .statusCode(200);
    }

    /** Transition cycle SCHEDULED → ACTIVE. */
    public static void activateCycle(String token, String cycleId) {
        given()
                .header("Authorization", "Bearer " + token)
                .contentType(ContentType.JSON)
                .when()
                .post("/cycles/" + cycleId + "/activate")
                .then()
                .statusCode(200);
    }

    // ── Reviews ───────────────────────────────────────────────────────────────

    /**
     * Creates a review of the given type. Returns the new reviewId.
     * Caller is responsible for choosing a token that is authorised
     * (ADMIN for any type; MANAGER for MANAGER+team; EMPLOYEE for own SELF).
     */
    public static String createReview(TestFixtures fx,
                                      String token,
                                      String cycleId,
                                      String templateId,
                                      String subjectUserId,
                                      String authorUserId,
                                      String reviewType) {
        Map<String, Object> body = new HashMap<>();
        body.put("cycleId", cycleId);
        body.put("templateId", templateId);
        body.put("subjectUserId", subjectUserId);
        body.put("authorUserId", authorUserId);
        body.put("reviewType", reviewType);

        String reviewId = given()
                .header("Authorization", "Bearer " + token)
                .contentType(ContentType.JSON)
                .body(body)
                .when()
                .post("/reviews")
                .then()
                .statusCode(201)
                .extract().path("reviewId");

        assertNotNull(reviewId, "POST /reviews must return a reviewId");
        fx.registerReviewForCleanup(reviewId);
        return reviewId;
    }

    /**
     * Convenience overload used by lifecycle tests when the author is the
     * subject themselves (SELF reviews).
     */
    public static String createSelfReview(TestFixtures fx,
                                          String token,
                                          String cycleId,
                                          String templateId,
                                          String userId) {
        return createReview(fx, token, cycleId, templateId, userId, userId, "SELF");
    }

    /**
     * Submits a review (sets status=COMPLETED). The supplied answers must
     * cover the required questions on the template.
     */
    public static Response submitReview(String token,
                                        String reviewId,
                                        Integer expectedVersion,
                                        String questionId,
                                        String answerText) {
        Map<String, Object> answer = new HashMap<>();
        answer.put("questionId", questionId);
        answer.put("response", answerText);

        Map<String, Object> body = new HashMap<>();
        body.put("status", "COMPLETED");
        body.put("answers", List.of(answer));
        if (expectedVersion != null) body.put("version", expectedVersion);

        return given()
                .header("Authorization", "Bearer " + token)
                .contentType(ContentType.JSON)
                .body(body)
                .when()
                .put("/reviews/" + reviewId);
    }

    // ── Misc ──────────────────────────────────────────────────────────────────

    private static String uniqueSuffix() {
        return E2EConfig.RUN_ID + "-" + UUID.randomUUID().toString().substring(0, 6);
    }
}
